/**
 * Stage0 - Software About & Release Information Generator
 * Computes dynamic release information:
 *   - Name: Stage0
 *   - Author: Anh Quoc Tran
 *   - Version: <current_package_version>__[partial_sha1_commit]_[arch_name]
 *   - Release date: Build date in yyyy-MM-dd
 *   - Copyright: Copyright @ <current_year> <Author name>. Licensed under the MIT license.
 * 
 * Synchronizes metadata across:
 *   1. Frontend config (frontend/config/about.ts)
 *   2. Backend embedded JSON (backend/about.json)
 *   3. NSIS Windows installer hook (backend/hooks.nsh) for Add/Remove Programs / Control Panel
 *   4. macOS Info.plist (backend/Info.plist)
 *   5. Tauri configuration (backend/tauri.conf.json)
 *   6. Cargo package metadata (backend/Cargo.toml)
 *   7. Node package metadata (package.json)
 *   8. Root LICENSE file
 */

import fs from 'fs';
import path from 'path';
import { execSync } from 'child_process';
import { fileURLToPath } from 'url';

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);
const ROOT_DIR = path.resolve(__dirname, '..');
const BACKEND_DIR = path.resolve(ROOT_DIR, 'backend');
const FRONTEND_DIR = path.resolve(ROOT_DIR, 'frontend');

export function computeAboutInfo(options = {}) {
  const pkgPath = path.resolve(ROOT_DIR, 'package.json');
  const pkg = JSON.parse(fs.readFileSync(pkgPath, 'utf8'));

  const name = 'Stage0';
  const author = 'Anh Quoc Tran';
  const packageVersion = pkg.version || '0.1.0';

  // 1. Partial SHA1 Commit
  let gitCommit = 'dev0000';
  try {
    gitCommit = execSync('git rev-parse --short HEAD', {
      cwd: ROOT_DIR,
      stdio: ['ignore', 'pipe', 'ignore'],
    }).toString().trim();
  } catch {
    gitCommit = process.env.GIT_COMMIT ? process.env.GIT_COMMIT.substring(0, 7) : '30991a1';
  }

  // 2. Target Architecture
  const rawArch = options.arch || process.env.TARGET_ARCH || process.arch || 'x64';
  let arch = 'x64';
  if (rawArch === 'arm64' || rawArch === 'aarch64') {
    arch = 'arm64';
  } else if (rawArch === 'x86' || rawArch === 'ia32') {
    arch = 'x86';
  } else {
    arch = 'x64';
  }

  // 3. Version format: <current_package_version>__[partial_sha1_commit]_[arch_name]
  const version = `${packageVersion}__${gitCommit}_${arch}`;

  // 4. Release date in yyyy-MM-dd
  const now = new Date();
  const year = String(now.getFullYear());
  const month = String(now.getMonth() + 1).padStart(2, '0');
  const day = String(now.getDate()).padStart(2, '0');
  const releaseDate = `${year}-${month}-${day}`;

  // 5. Copyright format: Copyright @ curreny_year Author name. Licensed under the MIT license.
  const copyright = `Copyright @ ${year} ${author}. Licensed under the MIT license.`;
  const license = 'MIT';
  const tagline = 'Local-First Virtual MR / PR Sandbox';
  const description =
    'Stage0 simulates 3-dot branch comparisons and merge conflict predictions completely in memory via git merge-tree with zero disk modifications.';
  const website = 'https://github.com/anhquoctran/stage0';

  return {
    name,
    author,
    packageVersion,
    gitCommit,
    arch,
    version,
    releaseDate,
    currentYear: year,
    copyright,
    license,
    tagline,
    description,
    website,
    os: process.platform === 'win32' ? 'windows' : process.platform === 'darwin' ? 'macos' : 'linux',
  };
}

export function syncAllMetadata(optionsOrInfo = {}) {
  const info = optionsOrInfo.name ? optionsOrInfo : computeAboutInfo(optionsOrInfo);

  // Ensure directories exist
  const frontendConfigDir = path.resolve(FRONTEND_DIR, 'config');
  if (!fs.existsSync(frontendConfigDir)) {
    fs.mkdirSync(frontendConfigDir, { recursive: true });
  }

  // 1. Generate frontend/config/about.ts
  const frontendAboutTs = `// Automatically generated by scripts/generate-about-info.mjs
// Do not edit manually. Run 'npm run dev' or 'npm run build' to regenerate.

export interface SoftwareAboutInfo {
  name: string;
  author: string;
  packageVersion: string;
  gitCommit: string;
  arch: string;
  version: string;
  releaseDate: string;
  currentYear: string;
  copyright: string;
  license: string;
  tagline: string;
  description: string;
  website: string;
  os?: string;
}

export const SOFTWARE_ABOUT: SoftwareAboutInfo = ${JSON.stringify(info, null, 2)};
`;
  fs.writeFileSync(path.resolve(frontendConfigDir, 'about.ts'), frontendAboutTs, 'utf8');

  // 2. Generate backend/about.json
  fs.writeFileSync(
    path.resolve(BACKEND_DIR, 'about.json'),
    JSON.stringify(info, null, 2) + '\n',
    'utf8'
  );

  // 3. Generate backend/hooks.nsh (NSIS hook for Windows Control Panel / Add-Remove Programs)
  const nsisHooksContent = `; ==============================================================================
; Stage0 NSIS Installer Hooks
; Automatically generated by scripts/generate-about-info.mjs
; Configures Add/Remove Programs (Control Panel) with full metadata
; ==============================================================================

!macro NSIS_HOOK_POSTINSTALL
  ; Set custom DisplayVersion in Windows Registry (Control Panel & Settings > Apps)
  WriteRegStr SHCTX "\${UNINSTKEY}" "DisplayName" "${info.name}"
  WriteRegStr SHCTX "\${UNINSTKEY}" "DisplayVersion" "${info.version}"
  WriteRegStr SHCTX "\${UNINSTKEY}" "Publisher" "${info.author}"
  WriteRegStr SHCTX "\${UNINSTKEY}" "Comments" "${info.name} - ${info.tagline}. Author: ${info.author}. ${info.copyright}"
  WriteRegStr SHCTX "\${UNINSTKEY}" "Contact" "${info.author}"
  WriteRegStr SHCTX "\${UNINSTKEY}" "HelpLink" "${info.website}"
  WriteRegStr SHCTX "\${UNINSTKEY}" "URLInfoAbout" "${info.website}"
!macroend
`;
  fs.writeFileSync(path.resolve(BACKEND_DIR, 'hooks.nsh'), nsisHooksContent, 'utf8');

  // 4. Generate backend/Info.plist for macOS bundle metadata
  const infoPlistContent = `<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<plist version="1.0">
<dict>
    <key>NSHumanReadableCopyright</key>
    <string>${info.copyright}</string>
    <key>CFBundleGetInfoString</key>
    <string>${info.name} ${info.version}, ${info.copyright}</string>
</dict>
</plist>
`;
  fs.writeFileSync(path.resolve(BACKEND_DIR, 'Info.plist'), infoPlistContent, 'utf8');

  // 5. Update backend/tauri.conf.json bundle metadata
  const tauriConfPath = path.resolve(BACKEND_DIR, 'tauri.conf.json');
  if (fs.existsSync(tauriConfPath)) {
    const tauriConf = JSON.parse(fs.readFileSync(tauriConfPath, 'utf8'));
    tauriConf.productName = info.name;
    tauriConf.version = info.packageVersion;

    tauriConf.bundle = tauriConf.bundle || {};
    tauriConf.bundle.active = true;
    tauriConf.bundle.targets = 'all';
    tauriConf.bundle.publisher = info.author;
    tauriConf.bundle.copyright = info.copyright;
    tauriConf.bundle.license = info.license;
    tauriConf.bundle.licenseFile = '../LICENSE';
    tauriConf.bundle.shortDescription = `${info.name} - ${info.tagline}`;
    tauriConf.bundle.longDescription = `${info.name} - ${info.description} Author: ${info.author}. ${info.copyright}`;
    tauriConf.bundle.homepage = info.website;

    // Windows NSIS hooks
    tauriConf.bundle.windows = tauriConf.bundle.windows || {};
    tauriConf.bundle.windows.nsis = tauriConf.bundle.windows.nsis || {};
    tauriConf.bundle.windows.nsis.installerHooks = 'hooks.nsh';

    // macOS Info.plist metadata file
    tauriConf.bundle.macOS = tauriConf.bundle.macOS || {};
    tauriConf.bundle.macOS.infoPlist = 'Info.plist';

    // Linux metadata
    tauriConf.bundle.linux = tauriConf.bundle.linux || {};
    tauriConf.bundle.linux.deb = tauriConf.bundle.linux.deb || {};
    tauriConf.bundle.linux.deb.section = 'devel';
    tauriConf.bundle.linux.deb.priority = 'optional';

    fs.writeFileSync(tauriConfPath, JSON.stringify(tauriConf, null, 2) + '\n', 'utf8');
  }

  // 6. Update backend/Cargo.toml
  const cargoTomlPath = path.resolve(BACKEND_DIR, 'Cargo.toml');
  if (fs.existsSync(cargoTomlPath)) {
    let cargoToml = fs.readFileSync(cargoTomlPath, 'utf8');
    if (!cargoToml.includes('authors =')) {
      cargoToml = cargoToml.replace(
        'description = "Stage0 - Local Virtual MR / PR Sandbox"',
        `description = "Stage0 - Local Virtual MR / PR Sandbox"\nauthors = ["${info.author}"]\nlicense = "${info.license}"`
      );
    } else {
      cargoToml = cargoToml.replace(/authors\s*=\s*\[[^\]]*\]/, `authors = ["${info.author}"]`);
    }
    fs.writeFileSync(cargoTomlPath, cargoToml, 'utf8');
  }

  // 7. Update package.json
  const pkgPath = path.resolve(ROOT_DIR, 'package.json');
  if (fs.existsSync(pkgPath)) {
    const pkg = JSON.parse(fs.readFileSync(pkgPath, 'utf8'));
    pkg.author = info.author;
    pkg.license = info.license;
    fs.writeFileSync(pkgPath, JSON.stringify(pkg, null, 2) + '\n', 'utf8');
  }

  // 8. Update LICENSE
  const licensePath = path.resolve(ROOT_DIR, 'LICENSE');
  const licenseText = `MIT License

Copyright (c) ${info.currentYear} ${info.author}

Permission is hereby granted, free of charge, to any person obtaining a copy
of this software and associated documentation files (the "Software"), to deal
in the Software without restriction, including without limitation the rights
to use, copy, modify, merge, publish, distribute, sublicense, and/or sell
copies of the Software, and to permit persons to whom the Software is
furnished to do so, subject to the following conditions:

The above copyright notice and this permission notice shall be included in all
copies or substantial portions of the Software.

THE SOFTWARE IS PROVIDED "AS IS", WITHOUT WARRANTY OF ANY KIND, EXPRESS OR
IMPLIED, INCLUDING BUT NOT LIMITED TO THE WARRANTIES OF MERCHANTABILITY,
FITNESS FOR A PARTICULAR PURPOSE AND NONINFRINGEMENT. IN NO EVENT SHALL THE
AUTHORS OR COPYRIGHT HOLDERS BE LIABLE FOR ANY CLAIM, DAMAGES OR OTHER
LIABILITY, WHETHER IN AN ACTION OF CONTRACT, TORT OR OTHERWISE, ARISING FROM,
OUT OF OR IN CONNECTION WITH THE SOFTWARE OR THE USE OR OTHER DEALINGS IN THE
SOFTWARE.
`;
  fs.writeFileSync(licensePath, licenseText, 'utf8');

  return info;
}

// Execute directly if run as CLI script
if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const info = syncAllMetadata();
  console.log(`\x1b[32m✓ Synchronized software about metadata successfully:\x1b[0m`);
  console.log(`  • Name        : \x1b[1m${info.name}\x1b[0m`);
  console.log(`  • Author      : \x1b[1m${info.author}\x1b[0m`);
  console.log(`  • Version     : \x1b[36m${info.version}\x1b[0m`);
  console.log(`  • Release Date: \x1b[33m${info.releaseDate}\x1b[0m`);
  console.log(`  • Copyright   : \x1b[2m${info.copyright}\x1b[0m`);
  console.log(`  • License     : \x1b[1m${info.license}\x1b[0m`);
}
